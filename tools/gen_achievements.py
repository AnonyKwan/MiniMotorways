#!/usr/bin/env python3
"""Turns the achievement table into web/js/achievements_data.js (ids, targets and rules only;
titles and wording are written in code)."""
import csv, sys, json
data, out = sys.argv[1], sys.argv[2]
rows = list(csv.DictReader(open(f"{data}/achievements.csv", encoding="utf-8-sig")))
KIND = {"Concrete": 0, "Bridge": 1, "Motorway": 2, "Traffic Light": 3, "Roundabout": 4, "Tunnel": 5}
items = []
for r in rows:
    modes = r["modes"]
    items.append([
        r["id"],
        "" if r["city"] in ("None", "") else r["city"].lower(),
        r["type"],
        int(float(r["value"])),
        KIND.get(r["upgrade"], 0),
        1 if modes.strip() == "Expert" else (2 if modes.strip() == "Endless" else 0),
    ])
body = json.dumps(items, separators=(",", ":"))
open(out, "w", encoding="utf-8", newline="\n").write(
    "// @generated by tools/gen_achievements.py. [id, city, type, value, upgradeKind, onlyMode(0 any,1 expert,2 endless)]\n"
    f"export const ACHIEVEMENTS = {body};\n")
print(len(items), "achievements")
