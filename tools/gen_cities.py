#!/usr/bin/env python3
"""Turns the design CSV tables into src/cities_data.rs (numbers only: no art, audio or code).
usage: gen_cities.py <data-dir> <out.rs>"""
import csv, sys, re, math, collections
data, out = sys.argv[1], sys.argv[2]
def rows(n): return list(csv.DictReader(open(f"{data}/{n}", encoding="utf-8-sig")))
KIND = {"Concrete":0,"Bridge":1,"Motorway":2,"Traffic Light":3,"Roundabout":4,"Tunnel":5}
cities = [c for c in rows("cities_table.csv") if c["bundle"] not in ("tutorial",)]
start = collections.defaultdict(list)
for r in rows("city_starting_packages.csv"):
    if r["type"] in KIND: start[r["bundle"]].append((KIND[r["type"]], int(r["amount"])))
plan = collections.defaultdict(list)
for r in rows("planned_buildings.csv"):
    if r["type"].startswith("Demand"):
        g = int(r["groupIndex"])
        plan[r["bundle"]].append((float(r["nominalSpawnDay"]), g if g >= 0 else 255))  # 255: any colour
rules = collections.defaultdict(list)
for r in rows("weekly_upgrades.csv"):
    cur = []
    if r["relativeCurve"]:
        for p in r["relativeCurve"].split(";"):
            x, y = p.strip().split(":"); cur.append((float(x), float(y)))
    rules[r["bundle"]].append((KIND[r["type"]], int(r["amount"]), int(r["additionalConcrete"]),
        float(r["baseWeight"]), float(r["weightIncreaseWhenNotOffered"]), int(r["maxPackageCount"]),
        int(r["startingWeek"]), int(r["lastWeek"]), cur))
osc = collections.defaultdict(dict)
for r in rows("demand_oscillation.csv"):
    osc[r["bundle"]][int(r["group"])] = (float(r["baseDemand"]), float(r["burstDemand"]), float(r["eccentricity"]), float(r["periodDays"]))
def f(x): return repr(float(x)) if "e" not in repr(float(x)) else f"{float(x):.6f}"
L = ["// @generated by tools/gen_cities.py from the design tables. Do not edit by hand.",
     "use crate::cities::{City, OscDef, UpgradeRule};", ""]
names = []
for c in cities:
    b = c["bundle"]; ident = b.upper()
    wa, ha = [float(x) for x in c["area"].split("x")]
    w, h = math.ceil(wa), math.ceil(ha)
    if not start[b] or int(c["groups"]) == 0: continue
    names.append(ident)
    L.append(f"const {ident}_START: &[(u8, u8)] = &[{', '.join(f'({k}, {a})' for k,a in start[b])}];")
    p = sorted(plan[b])
    L.append(f"const {ident}_PLAN: &[(f32, u8)] = &[{', '.join(f'({f(d)}, {g})' for d,g in p)}];")
    ru = ", ".join("UpgradeRule { kind: %d, amount: %d, add_concrete: %d, base: %s, inc: %s, max_count: %d, start_week: %d, last_week: %d, rel: &[%s] }" %
        (k,a,ac,f(bw),f(inc),mc,sw,lw, ", ".join(f"({f(x)}, {f(y)})" for x,y in cur)) for k,a,ac,bw,inc,mc,sw,lw,cur in rules[b])
    L.append(f"const {ident}_RULES: &[UpgradeRule] = &[{ru}];")
    groups = int(c["groups"])
    od = []
    for g in range(groups):
        o = osc[b].get(g, (0.8, 1.5, 12.0, 14.0))
        od.append("OscDef { base: %s, burst: %s, ecc: %s, period: %s }" % tuple(f(x) for x in o))
    L.append(f"const {ident}_OSC: &[OscDef] = &[{', '.join(od)}];")
    L.append("")
L.append("pub const CITIES: &[City] = &[")
for c in cities:
    b = c["bundle"]; ident = b.upper()
    if not start[b] or int(c["groups"]) == 0: continue
    wa, ha = [float(x) for x in c["area"].split("x")]
    L.append(f'    City {{ id: "{b}", name: "{c["city"]}", w: {math.ceil(wa)}, h: {math.ceil(ha)}, groups: {c["groups"]}, water: {c["water"]}, mountain: {c["mountain"]}, trees: {c["trees"]}, start: {ident}_START, plan: {ident}_PLAN, rules: {ident}_RULES, osc: {ident}_OSC }},')
L.append("];")
open(out, "w", encoding="utf-8").write("\n".join(L) + "\n")
print(len(names), "cities")
